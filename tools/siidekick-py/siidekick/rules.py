"""Built-in detection rules for Siidekick.

Each rule is a line-based regular expression with a plain-language explanation,
a suggested fix, and the fixer (if any) that can repair it automatically.

mode:
  auto   - fixed by adding new files or lines only
  edit   - fixed by a minimal edit to one existing line (needs owner approval)
  report - reported only; a person must decide the fix
"""

